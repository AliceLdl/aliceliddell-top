  function system() {
    var cfg = global.AICFG || {};
    var ov = cfg.promptOverrides || {};
    var base = (ov.system && String(ov.system).trim()) ? String(ov.system) : SYSTEM;
    /* 沙盘声明排在最前：先定框架，再谈规则 */
    var s = SAND + '\n\n' + base;
    if (cfg.godMode) s += GOD;
    /* 风格与语言固定在末尾，避免被改写后丢失 */
    return s + '\n\n【叙事风格】' + (STYLE[cfg.style] || STYLE.documentary) +
           '\n【语言】简体中文。';
  }

  function task(mode) {
    var ov = (global.AICFG && AICFG.promptOverrides) || {};
    var key = 'task_' + mode;
    if (ov[key] && String(ov[key]).trim()) return String(ov[key]);
    return TASKS[mode] || TASKS.national;
  }

  function build(mode, ctx, input, extra) {
    var cfg = global.AICFG || {};
    var lines = [];
    lines.push('【当前局势】');
    lines.push(typeof ctx === 'string' ? ctx : JSON.stringify(ctx));
    lines.push('');
    if (cfg.memory && String(cfg.memory).trim()) {
      lines.push('【前情提要（玩家自撰，视作已发生的事实）】');
      lines.push(String(cfg.memory).trim());
      lines.push('');
    }
    /* 叙事账本：玩家可见层 + 内部档案层 */
    if (cfg.ledgerInPrompt && global.AILEDGER && global.AIG && global.AIG.g()) {
      try {
        var brief = global.AILEDGER.briefForPrompt();
        if (brief) {
          lines.push('【态势简报（玩家看得到的账，你上一轮维护的）】');
          lines.push(brief);
          lines.push('');
        }
        var dos = global.AILEDGER.dossierForPrompt(cfg.contextLevel || 'standard');
        if (dos) {
          lines.push('【内部档案（玩家看不到，只有你能看；用来保持一致与因果）】');
          lines.push(dos);
          lines.push('');
        }
      } catch (e) {}
    }
    if (extra && extra.contextNote) {
      lines.push('【补充说明】' + extra.contextNote);
      lines.push('');
    }
    lines.push('【玩家输入】');
    lines.push(String(input || '').trim());
    lines.push('');
    lines.push(task(mode));
    if (cfg.godMode) lines.push(GOD_TAIL);
    lines.push(SAND_TAIL);
    lines.push('');
    lines.push('只输出 JSON。');
    return { system: system(), user: lines.join('\n') };
  }

